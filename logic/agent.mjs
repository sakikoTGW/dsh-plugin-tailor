/**
 * Agent layer generation: `agent.json`, `llms.txt` and the docs site.
 *
 * The contract is a scaffold: facts come from the repository, semantic fields
 * (tool inputs, expected validation output) become explicit open items instead
 * of invented prose.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import { collectFacts } from './facts.mjs'
import { readBrief } from './brief.mjs'
import { buildDocsSite, DOCS_MARKER } from './docs.mjs'
import { isFile, oneLine, readJson, readText, toPosix, writeInside } from './util.mjs'

const AGENT_MARKER = 'dsh-plugin-tailor/repo_agent'

/** @param {string} url */
function parseGitHub(url) {
  try {
    const parsed = new URL(url)
    if (parsed.hostname !== 'github.com' && parsed.hostname !== 'www.github.com') return null
    const parts = parsed.pathname.split('/').filter(Boolean)
    if (parts.length < 2) return null
    return { owner: parts[0], repo: parts[1].replace(/\.git$/, '') }
  } catch {
    return null
  }
}

/** @param {string} root */
function inferTools(root) {
  const file = join(root, 'host', 'register.js')
  if (!isFile(file)) return []
  const text = readText(file)
  const tools = []
  const pattern = /name:\s*'([a-z][a-z0-9_-]+)'\s*,\s*description:\s*\n?\s*'([^']+)'/g
  for (const match of text.matchAll(pattern)) {
    tools.push({ name: match[1], description: oneLine(match[2]).slice(0, 300) })
  }
  return tools
}

/** @param {any} facts */
function installCommand(facts, dshPlugin) {
  return dshPlugin
    ? `dsh plugin --profile <profile> add ${facts.name}`
    : `npm install ${facts.name}`
}

/** @param {any} facts @param {string} command */
function ciUrl(facts) {
  const github = facts.repo ? parseGitHub(facts.repo) : null
  if (!github) return null
  return `https://github.com/${github.owner}/${github.repo}/actions`
}

/**
 * @param {any} facts
 * @param {any} style
 * @param {{ docs?: boolean }} [options]
 * @returns {{ files: { path: string, content: string }[], todos: string[], warnings: string[], tools: number, pages: number }}
 */
export function buildAgentBundle(facts, style, options = {}) {
  const dshPlugin = isFile(join(facts.root, 'cordis.patch.yml')) || Boolean(readJson(join(facts.root, 'package.json'))?.dsh)
  const tools = inferTools(facts.root)
  const command = installCommand(facts, dshPlugin)
  const ci = ciUrl(facts)
  const todos = []

  if (tools.length === 0) todos.push('Tools: list the tool contracts by hand (name, input, output, read/write) in agent.json.')
  else todos.push('Tools: review the inferred names and descriptions; add inputs, outputs and read/write to agent.json.')
  todos.push('Validation: replace validation.expected with the real expected result.')
  if (!facts.scripts.test) todos.push('Validation: no test script in package.json; set validation.command and expected output.')
  if (!facts.repo) todos.push('Repository: add a repository URL to package.json so CI and reference links resolve.')
  if (!facts.docs.dir) todos.push('Docs: no docs/ directory; add reference Markdown pages, then rerun repo_agent.')
  const brief = readBrief(facts.root)
  if (!brief) todos.push('Brief: no .tailor/brief.json; run repo_brief before generating the agent layer.')
  else if ((brief.openQuestions ?? []).length > 0) todos.push(`Brief: ${brief.openQuestions.length} open question(s); answer them before applying the human-facing pages.`)

  const contract = {
    schema: `${facts.name}/agent-contract/v1`,
    generatedBy: AGENT_MARKER,
    name: facts.name,
    version: facts.version,
    purpose: oneLine(facts.description || facts.readme.firstParagraph || ''),
    install: {
      kind: dshPlugin ? 'dsh' : 'npm',
      command,
    },
    tools,
    validation: {
      command: facts.scripts.test ? 'npm test' : '',
      expected: 'TODO(tailor): expected result',
      ci: ci,
    },
    reference: 'docs/index.html',
    repository: facts.repo,
  }
  if (brief) {
    contract.brief = '.tailor/brief.json'
    contract.humanDecisions = {
      audience: brief.audience || null,
      voice: brief.voice || null,
      nonGoals: brief.nonGoals ?? [],
    }
  }
  if (todos.length > 0) contract.openItems = todos

  const llms = `<!-- generated by dsh-plugin-tailor repo_agent -->
# ${facts.name}

> ${oneLine(facts.description || facts.readme.firstParagraph || 'Repository contract for agents.')}

Version: ${facts.version ?? 'TODO(tailor)'}
Repository: ${facts.repo ?? 'TODO(tailor)'}
Install: ${command}
Validation: ${facts.scripts.test ? 'npm test' : 'TODO(tailor)'}
Brief: ${brief ? '.tailor/brief.json' : 'TODO(tailor): run repo_brief'}

## Tools

${tools.length > 0 ? tools.map((tool) => `- ${tool.name}: ${tool.description}`).join('\n') : '- TODO(tailor): list tool contracts in agent.json'}
${brief ? `\n## Human decisions\n\n- audience: ${brief.audience || '(open)'}\n- voice: ${brief.voice || '(open)'}\n- non-goals: ${(brief.nonGoals ?? []).length > 0 ? brief.nonGoals.join('; ') : '(open)'}\n` : ''}
## Reference

- agent.json: ./agent.json
- docs: ./docs/index.html
${ci ? `- CI: ${ci}\n` : ''}
${todos.length > 0 ? `## Open items\n\n${todos.map((todo) => `- ${todo}`).join('\n')}\n` : ''}`

  const site = options.docs === false
    ? { files: [], todos: [], warnings: [], pages: [] }
    : buildDocsSite(facts, style)
  const files = [
    { path: 'agent.json', content: `${JSON.stringify(contract, null, 2)}\n` },
    { path: 'llms.txt', content: llms },
    ...site.files.map((entry) => ({ path: toPosix(entry.path), content: entry.content })),
  ]
  return { files, todos: [...todos, ...site.todos], warnings: site.warnings, tools: tools.length, pages: site.pages?.length ?? 0 }
}

/** @param {string} content @param {string} path */
function generated(content, path) {
  if (path.endsWith('.json')) return content.includes(`"generatedBy": "${AGENT_MARKER}"`)
  if (path.endsWith('.html')) return content.includes(DOCS_MARKER)
  if (path.endsWith('.css')) return content.includes('dsh-plugin-tailor repo_agent')
  if (path.endsWith('.txt')) return content.startsWith('<!-- generated by')
  return content.includes(AGENT_MARKER)
}

/**
 * @param {string} root
 * @param {{ files: { path: string, content: string }[], todos: string[] }} bundle
 * @param {{ force?: boolean }} [options]
 * @returns {{ written: string[], skipped: string[], todos: string[] }}
 */
export function applyAgentBundle(root, bundle, options = {}) {
  const force = options.force === true
  const written = []
  const skipped = []
  const todos = [...bundle.todos]
  for (const entry of bundle.files) {
    const target = join(root, entry.path)
    if (existsSync(target)) {
      const existing = readFileSync(target, 'utf8')
      if (!force && !generated(existing, entry.path)) {
        skipped.push(entry.path)
        todos.push(`kept ${entry.path}: hand-written; pass force=true to overwrite`)
        continue
      }
      if (existing === entry.content) {
        skipped.push(entry.path)
        continue
      }
    }
    mkdirSync(dirname(join(root, entry.path)), { recursive: true })
    writeFileSync(writeInside(root, entry.path, entry.content).target, entry.content, 'utf8')
    written.push(entry.path)
  }
  return { written, skipped, todos }
}
