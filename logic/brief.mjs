/**
 * Repository brief: the shared judgment between the human and the agent.
 *
 * The brief is deliberately a scaffold. Facts seed the promise and acceptance;
 * only a human can answer audience, voice and non-goals. Until those are
 * answered, `repo_readme` and `repo_agent` should treat the brief as draft.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import { oneLine, toPosix } from './util.mjs'

export const BRIEF_MARKER = 'dsh-plugin-tailor/repo_brief'

/** @param {any} facts @param {any} style @param {Record<string, any>} answers */
export function draftBrief(facts, style, answers = {}) {
  const brief = {
    schema: 'dsh-plugin-tailor/brief/v1',
    generatedBy: BRIEF_MARKER,
    name: facts.name,
    version: facts.version,
    repo: facts.repo,
    promise: oneLine(facts.description || facts.readme.firstParagraph || ''),
    audience: '',
    voice: '',
    visual: {
      style: style.id,
      palette: style.palette,
    },
    nonGoals: [],
    acceptance: {
      test: facts.scripts.test ? 'npm test' : '',
      verify: `node bin/tailor.mjs verify . --style=${style.id}`,
      note: '',
    },
    openQuestions: [],
  }
  return mergeBrief(brief, answers)
}

/** @param {any} brief @param {Record<string, any>} answers */
export function mergeBrief(brief, answers = {}) {
  const next = {
    ...brief,
    visual: { ...(brief.visual ?? {}) },
    acceptance: { ...(brief.acceptance ?? {}) },
    nonGoals: Array.isArray(brief.nonGoals) ? [...brief.nonGoals] : [],
  }
  if (typeof answers.promise === 'string' && answers.promise.trim() !== '') next.promise = oneLine(answers.promise)
  if (typeof answers.audience === 'string' && answers.audience.trim() !== '') next.audience = oneLine(answers.audience)
  if (typeof answers.voice === 'string' && answers.voice.trim() !== '') next.voice = oneLine(answers.voice)
  if (Array.isArray(answers.nonGoals)) next.nonGoals = answers.nonGoals.map((item) => oneLine(item)).filter(Boolean)
  if (typeof answers.acceptance === 'string' && answers.acceptance.trim() !== '') next.acceptance.note = oneLine(answers.acceptance)
  next.openQuestions = questionsFor(next)
  return next
}

/** @param {any} brief */
export function questionsFor(brief) {
  const questions = []
  if (!brief.audience) questions.push('Audience: who is this repository for?')
  if (!brief.voice) questions.push('Voice: how should the README sound? (direct, dry, warm, playful…)')
  if (!brief.nonGoals || brief.nonGoals.length === 0) questions.push('Non-goals: what should this repository not become?')
  if (!brief.acceptance?.test) questions.push('Acceptance: what command proves the repository works?')
  return questions
}

/** @param {string} root */
export function readBrief(root) {
  const file = join(root, '.tailor', 'brief.json')
  if (!existsSync(file)) return null
  try {
    return JSON.parse(readFileSync(file, 'utf8'))
  } catch {
    return null
  }
}

/** @param {any} brief */
export function renderBrief(brief) {
  const line = (value, fallback) => (value ? String(value) : fallback)
  const list = (values, fallback) => (values && values.length > 0 ? values.map((item) => `- ${item}`).join('\n') : fallback)
  const status = brief.openQuestions.length === 0 ? 'ready' : 'draft'
  return `<!-- generated by dsh-plugin-tailor repo_brief -->
# ${brief.name} brief

Status: **${status}**${status === 'draft' ? ' — answer the open questions before repo_readme or repo_agent applies.' : ''}

## Promise

${line(brief.promise, 'TODO: one sentence a stranger can repeat.')}

## Audience

${line(brief.audience, 'TODO: who is this for, and what do they already know?')}

## Voice

${line(brief.voice, 'TODO: how should it sound? One or two concrete adjectives.')}

## Visual direction

- style: ${brief.visual?.style ?? 'product'}
- brand: ${brief.visual?.palette?.brand ?? 'undefined'}
- ink: ${brief.visual?.palette?.ink ?? 'undefined'}

## Non-goals

${list(brief.nonGoals, 'TODO: one thing this repository will not try to be.')}

## Acceptance

- test: ${line(brief.acceptance?.test, 'TODO')}
- verify: ${line(brief.acceptance?.verify, 'TODO')}
- note: ${line(brief.acceptance?.note, '—')}

## Open questions

${brief.openQuestions.length > 0 ? brief.openQuestions.map((question) => `- [ ] ${question}`).join('\n') : 'None. The brief is ready.'}
`
}

/**
 * @param {string} root
 * @param {any} brief
 * @param {{ force?: boolean }} [options]
 * @returns {{ written: string[], skipped: string[], todos: string[] }}
 */
export function applyBrief(root, brief, options = {}) {
  const force = options.force === true
  const written = []
  const skipped = []
  const todos = []
  const jsonPath = join(root, '.tailor', 'brief.json')
  const mdPath = join(root, '.tailor', 'BRIEF.md')
  mkdirSync(dirname(jsonPath), { recursive: true })
  const json = `${JSON.stringify(brief, null, 2)}\n`
  const md = renderBrief(brief)
  if (existsSync(jsonPath) && !force) {
    skipped.push(toPosix('.tailor/brief.json'))
    todos.push('kept .tailor/brief.json: hand-edited; pass force=true to regenerate')
  } else {
    writeFileSync(jsonPath, json, 'utf8')
    written.push('.tailor/brief.json')
  }
  if (existsSync(mdPath) && !force) {
    skipped.push(toPosix('.tailor/BRIEF.md'))
  } else {
    writeFileSync(mdPath, md, 'utf8')
    written.push('.tailor/BRIEF.md')
  }
  return { written, skipped, todos }
}
