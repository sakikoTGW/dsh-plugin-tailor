/**
 * @param {import('./facts.mjs').RepoFacts} facts
 * @param {'zh'|'en'} lang
 * @param {string[]} todos
 * @returns {string}
 */
function renderEvidence(facts, lang, todos) {
  const blocks = []
  const files = [facts.files.benchmark, facts.files.ablation].filter(Boolean)
  if (files.length > 0) {
    blocks.push(files.map((file) => `- [\`${file}\`](${file})`).join('\n'))
  }
  const seen = new Set()
  const rows = []
  for (const number of facts.numbers) {
    if (seen.has(number.raw)) continue
    seen.add(number.raw)
    rows.push(`- \`${number.from} → ${number.to}\` — ${truncate(number.raw, 110)}`)
    if (rows.length >= 5) break
  }
  if (rows.length > 0) blocks.push(rows.join('\n'))
  if (blocks.length === 0) {
    todos.push('evidence: add BENCHMARK.md or measured numbers with their method')
    return lang === 'zh' ? '- TODO：给真实测量（before/after、耗时、调用数），写清口径。' : '- TODO: add a real before/after measurement and state the method.'
  }
  return blocks.join('\n\n') + (lang === 'zh' ? '\n\n> 数字来自仓库内文件，口径见对应文档。' : '\n\n> Numbers come from files in this repository; see the linked document for method.')
}

