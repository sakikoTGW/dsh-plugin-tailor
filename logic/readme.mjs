/**
 * Preview a README draft without writing anything.
 *
 * @param {string} root
 * @param {string} styleId
 * @param {'zh'|'en'} lang
 * @returns {{ text: string, diff: string, todos: string[], warnings: string[], existing: boolean }}
 */
export function previewReadme(root, styleId = 'evidence', lang = 'zh') {
  const facts = collectFacts(root)
  const style = resolveStyle(styleId, loadStyles(facts.root))
  const draft = renderReadme(facts, style, lang)
  const target = lang === 'zh' ? 'README.md' : 'README.en.md'
  const existingPath = join(facts.root, target)
  const existing = existsSync(existingPath) ? readTextSafe(existingPath) : ''
  return {
    text: draft.text,
    diff: unifiedDiff(existing, draft.text, target),
    todos: draft.todos,
    warnings: styleWarnings(style, facts),
    existing: existing !== '',
  }
}

/**
 * Apply the draft to README.md / README.en.md.
 *
 * Safety:
 * - refuses if the worktree is dirty and `force` is not set;
 * - refuses to overwrite a README that was not generated by this tool unless
 *   `force` is set;
 * - writes a `.tailor/baseline.json` so `repo_verify` can report a delta.
 *
 * @param {string} root
 * @param {string} styleId
 * @param {'zh'|'en'|'both'} lang
 * @param {{ force?: boolean }} [options]
 * @returns {{ written: string[], skipped: string[], todos: string[], diff: string, warnings: string[] }}
 */
export function applyReadme(root, styleId = 'evidence', lang = 'both', options = {}) {
  const facts = collectFacts(root)
  const style = resolveStyle(styleId, loadStyles(facts.root))
  const force = options.force === true

  if (facts.git.present && facts.git.clean === false && !force) {
    throw new Error('worktree has uncommitted changes; commit/stash them or pass force=true')
  }

  const langs = lang === 'both' ? ['zh', 'en'] : [lang]
  const written = []
  const skipped = []
  let firstDiff = ''

  for (const current of langs) {
    const draft = renderReadme(facts, style, current)
    const target = current === 'zh' ? 'README.md' : 'README.en.md'
    const targetPath = resolveInside(facts.root, target)
    const existing = existsSync(targetPath) ? readTextSafe(targetPath) : ''
    if (existing !== '' && !GENERATED_MARKER.test(existing) && !force) {
      throw new Error(`${target} exists and was not generated by dsh-plugin-tailor; pass force=true to overwrite`)
    }
    if (existing === draft.text) {
      skipped.push(target)
      continue
    }
    mkdirSync(dirname(targetPath), { recursive: true })
    writeFileSync(targetPath, draft.text, 'utf8')
    written.push(target)
    if (firstDiff === '') firstDiff = unifiedDiff(existing, draft.text, target)
  }

  const baselineDir = join(facts.root, '.tailor')
  mkdirSync(baselineDir, { recursive: true })
  writeFileSync(join(baselineDir, 'baseline.json'), JSON.stringify({
    style: style.id,
    at: new Date().toISOString(),
    readme: facts.readme.path,
    todos: renderReadme(facts, style, 'zh').todos.length,
  }, null, 2) + '\n', 'utf8')

  return {
    written,
    skipped,
    todos: renderReadme(facts, style, langs[0]).todos,
    diff: firstDiff,
    warnings: styleWarnings(style, facts),
  }
}

/** @param {string} path */
function readTextSafe(path) {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return ''
  }
}
